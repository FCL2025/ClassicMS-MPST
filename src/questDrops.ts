/** 反查表：怪物 id → 任務道具 id 清單（模組載入時建一次）。 */
const MOB_TO_QUEST_ITEMS: ReadonlyMap<number, readonly number[]> = (() => {
  const map = new Map<number, number[]>();
  for (const [itemKey, mobIds] of Object.entries(QUEST_ITEM_DROPS)) {
    const itemId = Number(itemKey);
    for (const mobId of mobIds) {
      const list = map.get(mobId);
      if (list) list.push(itemId);
      else map.set(mobId, [itemId]);
    }
  }
  return map;
})();

/** 指定怪物會掉落的任務道具 id（沒有則回空陣列）。 */
export function questDropItemIdsForMob(mobId: number): readonly number[] {
  return MOB_TO_QUEST_ITEMS.get(mobId) ?? [];
}

